# ================= 2. 强制平衡生成三分类数据 =================
data = []

# 为了演示，我们生成 900 条数据，每类各 300 条（绝对平衡）
for i in range(900):
    def generate_sentence(word_list):
        num_words = random.randint(1, 3)
        words = random.sample(word_list, num_words)
        return "，".join(words) + "。"

    # 0~299: 正面 (2)
    if i < 300:
        text = generate_sentence(positive_words)
        label = 2
    # 300~599: 负面 (0)
    elif i < 600:
        text = generate_sentence(negative_words)
        label = 0
    # 600~899: 中评 (1)
    else:
        text = generate_sentence(neutral_words)
        label = 1
        
    data.append([text, label])

df = pd.DataFrame(data, columns=["评论内容", "情感标签"])
df.to_csv("comments.csv", index=False, encoding="utf-8-sig")
